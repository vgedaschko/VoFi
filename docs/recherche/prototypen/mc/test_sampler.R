spec <- read_stochastic_spec("spec.yaml")
t <- system.time(s <- sample_stochastic(spec))[[3]]; cat("Ziehung", t, "s\n")
print(round(sapply(s$parameters, function(v) c(mean = mean(v), p05 = quantile(v, .05, names = FALSE), p95 = quantile(v, .95, names = FALSE))), 4))
print(round(cor(s$parameters$construction_cost_factor, s$parameters$construction_delay_months, method="spearman"),3))
print(sapply(s$paths, function(x) round(c(nrow = nrow(x), mean_T = mean(x[, ncol(x)]), sd_T = sd(x[, ncol(x)])), 4)))
s2 <- sample_stochastic(spec); cat("identisch:", identical(s[1:3], s2[1:3]), "\n")
spec3 <- spec; spec3$parameters$neu <- list(dist="uniform", min=0, max=1)
s3 <- sample_stochastic(spec3)
cat("Zusatzparameter ändert übrige Ziehungen nicht:", identical(s$parameters$heat_pump_lifetime, s3$parameters$heat_pump_lifetime), identical(s$paths, s3$paths), "\n")
